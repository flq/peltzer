// "none": cursor goes behind the parens; otherwise it goes between them
export type StepArgs = "required" | "optional" | "none";

export interface StepInfo {
  name: string;
  args: StepArgs;
  description: string;
}

function step(name: string, args: StepArgs, description: string): StepInfo {
  return { name, args, description };
}

